-- ---------- Usuarios ----------
CREATE TABLE IF NOT EXISTS administrador (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo     VARCHAR(100) NOT NULL UNIQUE,
  contrasena VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS cliente (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo     VARCHAR(100) NOT NULL UNIQUE,
  contrasena VARCHAR(100) NOT NULL
);

-- ---------- Inventario ----------
CREATE TABLE IF NOT EXISTS distribuidor (
  id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL
);

CREATE TABLE IF NOT EXISTS producto (
  id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre             VARCHAR(150) NOT NULL,
  categoria          VARCHAR(100),
  precio             NUMERIC(10,2) NOT NULL DEFAULT 0,
  cantidad           INT NOT NULL DEFAULT 0,
  imagen             TEXT,
  fecha_modificacion TIMESTAMP DEFAULT NOW()
);

-- ---------- RH ----------
CREATE TABLE IF NOT EXISTS empleado (
  id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           VARCHAR(150) NOT NULL,
  puesto           VARCHAR(100),
  horario          VARCHAR(100),
  administrador_id INT REFERENCES administrador(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS asistencia (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empleado_id  INT NOT NULL REFERENCES empleado(id) ON DELETE CASCADE,
  fecha        DATE NOT NULL,
  hora_entrada TIME,
  hora_salida  TIME,
  estado       VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS nomina (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empleado_id   INT NOT NULL REFERENCES empleado(id) ON DELETE CASCADE,
  periodo       VARCHAR(50),
  monto_a_pagar NUMERIC(10,2) NOT NULL
);

-- ---------- Finanzas ----------
CREATE TABLE IF NOT EXISTS movimiento_financiero (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_movimiento   VARCHAR(10) NOT NULL CHECK (tipo_movimiento IN ('ingreso', 'egreso')),
  monto             NUMERIC(10,2) NOT NULL,
  fecha             TIMESTAMP NOT NULL DEFAULT NOW(),
  descripcion       VARCHAR(255),
  referencia_paypal VARCHAR(100),
  nomina_id         INT REFERENCES nomina(id) ON DELETE SET NULL
);

-- ---------- Ventas ----------
CREATE TABLE IF NOT EXISTS factura (
  id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id      INT REFERENCES cliente(id) ON DELETE SET NULL,
  orden_paypal_id VARCHAR(100),
  fecha_emision   TIMESTAMP NOT NULL DEFAULT NOW(),
  archivo_xml     TEXT
);

